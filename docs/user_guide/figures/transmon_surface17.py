def _legend(ax, p: Palette, x: float, y: float, dy: float, size: float = 7.0) -> None:
    """The three groups, each with its marker, color and name, from (*x*, *y*) down."""
    for k, g in enumerate(GROUPS):
        members = BY_GROUP[g]
        shade = color(p, members[0].label)
        ax.plot(
            [x],
            [y - k * dy],
            MARKERS[g],
            ms=size,
            color=shade,
            mec=shade,
            mfc=shade + "33",
            mew=1.3,
            clip_on=False,
            transform=ax.transAxes,
        )
        ax.text(
            x + 0.035,
            y - k * dy,
            f"{PLURALS[g]}: {members[0].label} to {members[-1].label}, "
            f"indices {members[0].index} to {members[-1].index}",
            transform=ax.transAxes,
            va="center",
            fontsize=8.5,
            color=p.text,
        )


def layout() -> None:
    where = lattice(SYSTEM)
    partners: dict[int, list[int]] = {}
    for c in SYSTEM.couplings:
        partners.setdefault(c.qudits[0], []).append(c.qudits[1])

    def figure(p: Palette):
        with plt.rc_context(_rc(p)):
            fig = plt.figure(figsize=(WIDTH_IN, 3.9))
        ax = fig.add_axes((0.0, 0.0, 0.54, 1.0))
        ax.axis("off")
        ax.set_aspect("equal")
        for auxiliary, coupled in partners.items():
            shade = color(p, LABEL[auxiliary])
            if len(coupled) == 2:
                corners = [where[auxiliary], *(where[d] for d in coupled)]
            else:
                cx, cy = where[auxiliary]
                corners = sorted(
                    (where[d] for d in coupled),
                    key=lambda xy: math.atan2(xy[1] - cy, xy[0] - cx),
                )
            ax.add_patch(Polygon(corners, closed=True, color=shade, alpha=0.13, lw=0))
            for d in coupled:
                (x0, y0), (x1, y1) = where[auxiliary], where[d]
                ax.plot([x0, x1], [y0, y1], color=p.rule, lw=1.1, zorder=2)
        for q in QUDITS:
            x, y = where[q.index]
            shade = color(p, q.label)
            ax.plot(
                [x],
                [y],
                MARKERS[group(q.label)],
                ms=25 if group(q.label) != "Z" else 21,
                color=shade,
                mfc=p.surface,
                mec=shade,
                mew=1.6,
                zorder=3,
            )
            ax.text(
                x, y - 0.045, q.label, ha="center", va="center", fontsize=8.5, color=p.text,
                fontweight="bold", zorder=4,
            )  # fmt: skip
            ax.text(
                x, y + 0.1, str(q.index), ha="center", va="center", fontsize=6.5, color=p.muted,
                zorder=4,
            )  # fmt: skip
        ax.set_xlim(-0.85, 2.85)
        ax.set_ylim(2.85, -0.85)

        key = fig.add_axes((0.56, 0.0, 0.44, 1.0))
        key.axis("off")
        _legend(key, p, 0.03, 0.78, 0.085)
        lines = [
            "In each marker: the label, and under it",
            "the index a program addresses.",
            "",
            f"A line is a coupling: {len(SYSTEM.couplings)} in all, each",
            "between an auxiliary and a data qudit.",
            "",
            "A shaded patch is one stabilizer: an",
            "auxiliary and the data qudits it checks.",
        ]
        key.text(
            0.0, 0.5, "\n".join(lines), transform=key.transAxes, va="top", fontsize=8.5,
            color=p.muted, linespacing=1.45,
        )  # fmt: skip
        return fig

    said = "; ".join(
        f"{LABEL[a]} (index {a}) couples to "
        + ", ".join(LABEL[d] for d in sorted(coupled, key=lambda d: LABEL[d]))
        for a, coupled in sorted(partners.items())
    )
    alt = (
        f"The {len(QUDITS)} qudits of transmon_surface17 on a square lattice. The "
        f"{len(BY_GROUP['D'])} data qudits {BY_GROUP['D'][0].label} to {BY_GROUP['D'][-1].label}, "
        f"indices {BY_GROUP['D'][0].index} to {BY_GROUP['D'][-1].index}, fill a grid row by row. "
        f"Each of the {len(partners)} auxiliary qudits sits between the data qudits it couples "
        f"to: {said}."
    )
    save_themed(
        figure,
        "surface17_layout",
        title="The lattice of transmon_surface17",
        desc=alt,
        directory=HERE,
    )


def frequencies() -> None:
    rows = [q for g in GROUPS for q in BY_GROUP[g]]

    def figure(p: Palette):
        fig, ax = plot_axes(p, height_in=0.2 * len(rows) + 1.5)
        y, ticks = 0.0, []
        for g in GROUPS:
            y -= 1.6
            ax.text(
                0.0, y, PLURALS[g], transform=ax.get_yaxis_transform(), ha="left",
                va="center", fontsize=8, color=color(p, g), fontweight="bold",
            )  # fmt: skip
            for q in BY_GROUP[g]:
                y -= 1.0
                ticks.append((y, q.label))
                shade = color(p, q.label)
                f01 = q.frequency_hz / 1e9
                f12 = SYSTEM.transition_freq[q.index, 1, 2] / 1e9
                resonator = q.readout.frequency_hz / 1e9
                ax.plot([f12, resonator], [y, y], color=p.grid, lw=0.8, zorder=1)
                ax.plot([f12], [y], "|", ms=7, mew=1.4, color=shade, zorder=3)
                ax.plot([f01], [y], MARKERS[g], ms=6, color=shade, mec=shade, zorder=3)
                ax.plot(
                    [resonator], [y], MARKERS[g], ms=6, mfc=p.surface, mec=shade, mew=1.3, zorder=3
                )
        ax.set_yticks([t for t, _ in ticks], [name for _, name in ticks])
        ax.tick_params(axis="y", labelcolor=p.text)
        ax.set_ylim(y - 0.8, -0.7)
        ax.grid(axis="y", visible=False)
        ax.grid(axis="x", color=p.grid)
        ax.set_xlabel("frequency (GHz)")
        # What each mark is, said once, above the plot.
        key = (("|", "1-2 transition", {"mew": 1.4}), ("o", "0-1 transition (filled)", {}),
               ("o", "readout resonator (hollow)", {"mfc": p.surface, "mew": 1.3}))  # fmt: skip
        for k, (mark, word, how) in enumerate(key):
            x = 0.3 * k
            ax.plot(
                [x + 0.012], [1.03], mark, ms=6.5, color=p.muted, mec=p.muted,
                transform=ax.transAxes, clip_on=False, **how,
            )  # fmt: skip
            ax.text(
                x + 0.03, 1.03, word, transform=ax.transAxes, va="center", fontsize=8.5,
                color=p.muted,
            )  # fmt: skip
        return fig

    def said(g: str) -> str:
        members = BY_GROUP[g]
        return (
            f"the {PLURALS[g]} have their 0-1 transition at "
            f"{spread([q.frequency_hz / 1e9 for q in members], '{:.3f}')} GHz and their "
            f"resonators at {spread([q.readout.frequency_hz / 1e9 for q in members], '{:.3f}')} GHz"
        )

    alt = (
        f"The frequencies of the {len(rows)} qudits, one row each, on an axis in GHz: the 0-1 "
        "transition, the 1-2 transition below it by the anharmonicity, and the readout "
        "resonator. " + sentence("; ".join(said(g) for g in GROUPS))
    )
    save_themed(
        figure,
        "surface17_frequencies",
        title="The frequency plan of transmon_surface17",
        desc=alt,
        directory=HERE,
    )


def feedline_figure() -> None:
    groups = feedlines(SYSTEM)

    def figure(p: Palette):
        fig, ax = plot_axes(p, height_in=0.52 * len(groups) + 0.6)
        for k, members in enumerate(groups.values()):
            y = -k
            xs = [SYSTEM.physical_qudits[i].readout.frequency_hz / 1e9 for i in members]
            ax.plot([min(xs), max(xs)], [y, y], color=p.rule, lw=1.0, zorder=1)
            for i, x in zip(members, xs, strict=True):
                shade = color(p, LABEL[i])
                ax.plot(
                    [x], [y], MARKERS[group(LABEL[i])], ms=7, mfc=p.surface, mec=shade, mew=1.4,
                    zorder=3,
                )  # fmt: skip
                ax.annotate(
                    LABEL[i], (x, y), xytext=(0, 7), textcoords="offset points", ha="center",
                    va="bottom", fontsize=8, color=p.text,
                )  # fmt: skip
        ax.set_yticks([-k for k in range(len(groups))], [feedline_name(n) for n in groups])
        ax.tick_params(axis="y", labelcolor=p.text)
        ax.set_ylim(-len(groups) + 0.55, 0.75)
        ax.grid(axis="y", visible=False)
        ax.grid(axis="x", color=p.grid)
        ax.set_xlabel("readout resonator frequency (GHz)")
        return fig

    said = "; ".join(
        f"{feedline_name(name)}: "
        + ", ".join(
            f"{LABEL[i]} at {ghz(SYSTEM.physical_qudits[i].readout.frequency_hz)}"
            for i in sorted(members, key=lambda i: SYSTEM.physical_qudits[i].readout.frequency_hz)
        )
        for name, members in groups.items()
    )
    alt = (
        f"The readout resonators of the {len(groups)} feedlines, one row per feedline, on an "
        f"axis in GHz. {sentence(said)}"
    )
    save_themed(
        figure,
        "surface17_feedlines",
        title="The readout feedlines of transmon_surface17",
        desc=alt,
        directory=HERE,
    )


def round_figure() -> None:
    scheduled = cycle()
    timeline = Timeline.of(scheduled)
    index = {name: i for i, name in LABEL.items()}
    qudit_of = {lane.key: index[lane.label.split()[0]] for lane in timeline.lanes}
    order = [q.index for g in GROUPS for q in BY_GROUP[g]]
    # A row per qudit, top to bottom, with a gap between the groups.
    row, y = {}, 0.0
    for g in GROUPS:
        for q in BY_GROUP[g]:
            row[q.index] = y
            y -= 1.0
        y -= 0.5
    # Each CZ slot is a wait on its two qudits; the slots of one step start together.
    starts = sorted({w.start_ns for w in timeline.waits})
    assert len(starts) == len(CZ_LAYERS)
    slots = []
    for w in timeline.waits:
        me = qudit_of[w.lane]
        layer = CZ_LAYERS[starts.index(w.start_ns)]
        auxiliary, data = next(pair for pair in layer if me in pair)
        slots.append((me, auxiliary if me == data else data, auxiliary, w.start_ns, w.end_ns))
    end = max(pl.end_ns for pl in timeline.pulses)
    peak = max(max(map(abs, pl.i)) for pl in timeline.pulses)

    def figure(p: Palette):
        fig, ax = plot_axes(p, height_in=0.215 * len(order) + 1.0)
        for i in order:
            ax.axhline(row[i], color=p.grid, lw=0.8, zorder=1)
        for me, partner, auxiliary, a, b in slots:
            shade = color(p, LABEL[auxiliary])
            ax.add_patch(
                Rectangle(
                    (a, row[me] + 0.08), b - a, 0.66, fc=shade + "30", ec=shade, lw=0.8, zorder=2
                )
            )
            ax.text(
                (a + b) / 2, row[me] + 0.41, LABEL[partner], ha="center", va="center",
                fontsize=6.5, color=p.text, zorder=3,
            )  # fmt: skip
        for pl in timeline.pulses:
            base = row[qudit_of[pl.lane]]
            ys = [base + 0.8 * abs(v) / peak for v in pl.i]
            ax.fill_between(pl.t_ns, base, ys, color=p.drive, alpha=0.3, lw=0, zorder=2)
            ax.plot(pl.t_ns, ys, color=p.drive, lw=1.2, zorder=3)
        for k, a in enumerate(starts, 1):
            b = next(s[4] for s in slots if s[3] == a)
            ax.text((a + b) / 2, 0.95, str(k), ha="center", va="bottom", fontsize=8, color=p.muted)
        ax.text(-12, 0.95, "CZ step", ha="right", va="bottom", fontsize=8, color=p.muted)
        ax.set_yticks([row[i] + 0.3 for i in order], [LABEL[i] for i in order])
        for tick, i in zip(ax.get_yticklabels(), order, strict=True):
            tick.set_color(color(p, LABEL[i]))
            tick.set_fontweight("bold")
        ax.set_ylim(min(row.values()) - 0.25, 1.9)
        ax.set_xlim(0, end * 1.005)
        ax.grid(axis="y", visible=False)
        ax.grid(axis="x", color=p.grid)
        ax.set_xlabel("time (ns)")
        return fig

    drives = sorted(timeline.pulses, key=lambda pl: pl.start_ns)
    slot = slots[0][4] - slots[0][3]
    alt = (
        f"The schedule of one error correction cycle on the drive lines of the {len(order)} "
        f"qudits, {end:g} ns long. {len(CZ_LAYERS)} CZ steps of {slot:g} ns follow each other, "
        f"the first from {starts[0]:g} ns and the last from {starts[-1]:g} ns; in each step, "
        f"{len(CZ_LAYERS[0])} auxiliary-data pairs wait together, each box naming its partner. "
        f"Steps 1 to {len(CZ_LAYERS) // 2} are on the Z auxiliaries and steps "
        f"{len(CZ_LAYERS) // 2 + 1} to {len(CZ_LAYERS)} on the X auxiliaries. Between the steps "
        f"are {len(drives)} drive pulses of "
        f"{drives[0].end_ns - drives[0].start_ns:g} ns: quarter turns on the auxiliaries "
        "around their four steps, quarter turns on the data qudits around the X steps, and "
        "an echo on every data qudit in the middle of each half."
    )
    save_themed(
        figure,
        "surface17_round",
        title="One error correction cycle on transmon_surface17",
        desc=alt,
        directory=HERE,
    )


