def ghz(hz: float) -> str:
    return f"{hz / 1e9:.3f}"


def mhz(hz: float) -> str:
    return f"{hz / 1e6:g}"


def spread(values, form="{:g}") -> str:
    """The least and greatest of *values*, as ``a to b``."""
    low, high = form.format(min(values)), form.format(max(values))
    return low if low == high else f"{low} to {high}"


def sentence(text: str) -> str:
    """*text* as a sentence: its first letter a capital, and a full stop."""
    return text[0].upper() + text[1:] + "."


def feedline_name(key: str) -> str:
    return key.replace("_", " ")


def cycle():
    """The scheduled cycle of the surface-code example, which this runs."""
    with contextlib.redirect_stdout(io.StringIO()):
        import transmon_surface17_surface_code_cycle as example
    return example.scheduled


