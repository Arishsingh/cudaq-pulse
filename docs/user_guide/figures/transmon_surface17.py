def values() -> dict[str, str]:
    """Each substitution of the page, by name."""
    x = QUDITS[0].get_calibration(pulse.gates.X)
    x12 = QUDITS[0].get_calibration(pulse.gates.X, transition=(1, 2))
    readouts = {g: BY_GROUP[g][0].get_calibration(pulse.gates.READOUT) for g in GROUPS}
    czs = [c.get_calibration(pulse.gates.CZ) for c in SYSTEM.couplings]
    calibration = SYSTEM.calibration
    record = feedline_record(SYSTEM)
    scheduled = cycle()
    indices = {g: [q.index for q in BY_GROUP[g]] for g in GROUPS}
    auxiliaries = [q for g in GROUPS[1:] for q in BY_GROUP[g]]
    gap_hz = min(q.frequency_hz for q in auxiliaries) - max(q.frequency_hz for q in BY_GROUP["D"])
    found = {
        "qudits": str(len(QUDITS)),
        "couplings": str(len(SYSTEM.couplings)),
        "clock": f"{SYSTEM.clock_ghz:g} GHz",
        "calibration": calibration.name,
        "run": calibration.measurement_run,
        "run-is": calibration.measurement_runs()[calibration.measurement_run],
        "f-data": spread([q.frequency_hz / 1e9 for q in BY_GROUP["D"]], "{:.3f}") + " GHz",
        "f-aux": spread([q.frequency_hz / 1e9 for g in "XZ" for q in BY_GROUP[g]], "{:.3f}")
        + " GHz",
        "f-gap": f"{gap_hz / 1e9:.2f} GHz",
        "f-readout": spread([q.readout.frequency_hz / 1e9 for q in QUDITS], "{:.3f}") + " GHz",
        "anharmonicity": spread([q.anharmonicity_hz / 1e6 for q in QUDITS]) + " MHz",
        "t1": spread([q.t1_us for q in QUDITS]) + " µs",
        "t2-star": spread([q.t2_star_us for q in QUDITS]) + " µs",
        "t2-echo": spread([q.t2_echo_us for q in QUDITS]) + " µs",
        "exchange": spread([c.strength_hz / 1e6 for c in SYSTEM.couplings], "{:.2f}") + " MHz",
        "x-ns": f"{x.duration_ns:g} ns",
        "x-sigma": f"{x.sigma_ns:g} ns",
        "x12-ns": f"{x12.duration_ns:g} ns",
        "readout-data-ns": f"{readouts['D'].duration_ns:g} ns",
        "readout-aux-ns": spread([readouts[g].duration_ns for g in "XZ"]) + " ns",
        "cz-ns": spread([cz.duration_ns for cz in czs]) + " ns",
        "cz-buffer-ns": spread([cz.buffer_ns for cz in czs]) + " ns",
        "cz-steps": str(len(CZ_LAYERS)),
        "cz-per-step": spread([len(layer) for layer in CZ_LAYERS]),
        "feedlines": str(len(record["groups"])),
        "feedline-sizes": spread([len(g["qudits"]) for g in record["groups"].values()]),
        "feedline-kind": record["kind"],
        "feedline-spacing": f"{min(g['min_spacing_mhz'] for g in record['groups'].values())} MHz",
        "round-ns": f"{scheduled.duration / pulse.ns:g} ns",
    }
    for g in GROUPS:
        key = {"D": "data", "X": "x", "Z": "z"}[g]
        found[f"{key}-count"] = str(len(BY_GROUP[g]))
        found[f"{key}-labels"] = f"{BY_GROUP[g][0].label} to {BY_GROUP[g][-1].label}"
        found[f"{key}-indices"] = f"{indices[g][0]} to {indices[g][-1]}"
    return found


# ── The tables ──────────────────────────────────────────────────────────────


def table(title: str, widths: list[int], header: list[str], rows: list[list[str]]) -> str:
    lines = [
        f".. list-table:: {title}",
        "   :header-rows: 1",
        f"   :widths: {' '.join(map(str, widths))}",
        "",
    ]
    for row in [header, *rows]:
        for k, cell in enumerate(row):
            lines.append(f"   {'* -' if k == 0 else '  -'} {cell}")
    return "\n".join(lines) + "\n"


def tables() -> dict[str, str]:
    """Each table of the page, as reStructuredText, by name."""
    qudits = table(
        "The qudits of ``transmon_surface17``",
        [8, 8, 16, 14, 16, 14, 16],
        [
            "Index",
            "Label",
            "Group",
            "0-1 frequency (GHz)",
            "Anharmonicity (MHz)",
            "Readout resonator (GHz)",
            "Feedline",
        ],
        [
            [
                str(q.index),
                q.label,
                NAMES[group(q.label)],
                ghz(q.frequency_hz),
                mhz(q.anharmonicity_hz),
                ghz(q.readout.frequency_hz),
                feedline_name(FEEDLINE[q.index]),
            ]
            for q in QUDITS
        ],
    )
    coherence = table(
        "Coherence, thermal population and readout assignment error",
        [10, 14, 14, 16, 22, 24],
        [
            "Label",
            "T1 (µs)",
            "T2* (µs)",
            "T2 echo (µs)",
            "Thermal population (%)",
            "Readout assignment error (%)",
        ],
        [
            [
                q.label,
                f"{q.t1_us:g}",
                f"{q.t2_star_us:g}",
                f"{q.t2_echo_us:g}",
                f"{100 * q.thermal_population:.1f}",
                f"{100 * q.readout.error_1to0:.2f}",
            ]
            for q in QUDITS
        ],
    )
    # One row per gate where every group's calibration says the same, else
    # one per group.
    per_group: dict[str, dict[str, list[str]]] = {}
    for g in GROUPS:
        q = BY_GROUP[g][0]
        x = q.get_calibration(pulse.gates.X)
        x90 = q.get_calibration(pulse.gates.X90)
        x12 = q.get_calibration(pulse.gates.X, transition=(1, 2))
        measure = q.get_calibration(pulse.gates.READOUT)
        found = {
            "``X``": [type(x).__name__, f"{x.duration_ns:g}", f"sigma {x.sigma_ns:g} ns"],
            "``X90``": [
                type(x90).__name__,
                f"{x90.duration_ns:g}",
                f"``X`` at {x90.amplitude / x.amplitude:g} of its amplitude",
            ],
            "``X``, 1-2 transition": [
                type(x12).__name__,
                f"{x12.duration_ns:g}",
                f"sigma {x12.sigma_ns:g} ns",
            ],
            "``READOUT``": [
                type(measure).__name__,
                f"{measure.duration_ns:g}",
                f"sigma {measure.sigma_ns:g} ns, integrated for {measure.integration_ns:g} ns",
            ],
        }
        for gate, cells in found.items():
            per_group.setdefault(gate, {})[g] = cells
    gate_rows = []
    for gate, by_group in per_group.items():
        distinct = list(dict.fromkeys(map(tuple, by_group.values())))
        for cells in distinct:
            on = [PLURALS[g] for g in GROUPS if tuple(by_group[g]) == cells]
            where = "every qudit" if len(distinct) == 1 else "the " + " and ".join(on)
            gate_rows.append([gate, where, f"``{cells[0]}``", *cells[1:]])
    czs = [c.get_calibration(pulse.gates.CZ) for c in SYSTEM.couplings]
    gate_rows.append(
        [
            "``CZ``",
            f"each of the {len(czs)} couplings",
            f"``{type(czs[0]).__name__}``",
            spread([cz.duration_ns for cz in czs]),
            f"buffers of {spread([cz.buffer_ns for cz in czs])} ns included; no pulse is sent",
        ]
    )
    gates = table(
        "The calibrated gates",
        [18, 20, 16, 14, 32],
        ["Gate", "On", "Calibration", "Duration (ns)", "Notes"],
        gate_rows,
    )
    steps = table(
        "The CZ steps of one cycle (``CZ_LAYERS``)",
        [10, 20, 70],
        ["Step", "Stabilizers", "CZs, auxiliary-data"],
        [
            [
                str(k),
                " and ".join(sorted({group(LABEL[a]) for a, _ in layer})),
                ", ".join(f"{LABEL[a]}-{LABEL[d]}" for a, d in layer),
            ]
            for k, layer in enumerate(CZ_LAYERS, 1)
        ],
    )
    couplings = table(
        "The couplings and their CZs",
        [14, 12, 24, 28, 22],
        [
            "Pair",
            "CZ step",
            "Exchange at idle (MHz)",
            "CZ interaction frequency (GHz)",
            "CZ duration (ns)",
        ],
        [
            [
                f"{LABEL[c.qudits[0]]}-{LABEL[c.qudits[1]]}",
                str(STEP[tuple(c.qudits)]),
                f"{c.strength_hz / 1e6:.2f}",
                ghz(c.get_calibration(pulse.gates.CZ).interaction_frequency_hz),
                f"{c.get_calibration(pulse.gates.CZ).duration_ns:g}",
            ]
            for c in SYSTEM.couplings
        ],
    )
    return {
        "qudits": qudits,
        "coherence": coherence,
        "gates": gates,
        "steps": steps,
        "couplings": couplings,
    }


def include() -> str:
    """The file the page includes."""
    parts = [_HEADER]
    parts += [f".. |s17-{name}| replace:: {value}" for name, value in values().items()]
    for name, text in tables().items():
        parts += [f"\n.. start of {name}\n", text.rstrip("\n"), f"\n.. end of {name}"]
    return "\n".join(parts) + "\n"


